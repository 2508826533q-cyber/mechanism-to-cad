"""Configure this clone for its current Windows Python/CAD environment; no software installation."""
import argparse,sys
from pathlib import Path
from check_environment import check
from core import write
def configure(install=None,force=False):
    root=Path(__file__).resolve().parents[1];dest=root/'local_environment.json'
    if dest.exists() and not force:raise FileExistsError('local_environment.json exists; inspect it or explicitly pass --force')
    env=check();required=('cadgen','numpy','matplotlib','Pillow','pywin32')
    missing=[k for k in required if not env['packages'].get(k)]
    if missing:raise RuntimeError('Interpreter is missing '+', '.join(missing)+'. Reuse a suitable existing environment, or install requirements.txt into a chosen virtual environment.')
    if not install:
        candidates=env['programs']['solidworks']
        install=str(Path(candidates[0]).parent) if candidates else None
    if not install:raise RuntimeError('SOLIDWORKS not found. Pass --solidworks-install with its installation directory.')
    folder=Path(install)
    for name in ('sldworks.tlb','swconst.tlb','swmotionstudy.tlb'):
        if not (folder/name).is_file():raise FileNotFoundError(f'Missing {folder/name}')
    config={'python':sys.executable,'solidworks_install':str(folder.resolve()),'note':'Local configuration, generated by configure_environment.py; do not commit this file.'}
    write(dest,config);print('Configured',dest)
    return config
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--solidworks-install');p.add_argument('--force',action='store_true');a=p.parse_args();configure(a.solidworks_install,a.force)
